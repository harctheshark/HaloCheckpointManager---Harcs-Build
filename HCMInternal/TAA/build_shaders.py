# build_shaders.py - precompiles HCM_TAA.hlsl (Halo 2 TAA resolve) and HCM_TAAProxy.hlsl (v2: the object motion pass) with
# the Windows SDK's fxc into Generated\TAAShaders.h (H2TAA.cpp, 2026-11-23). Run it again only when a .hlsl here changes;
# the output is checked in.
# usage: python build_shaders.py [path to fxc.exe]
import glob, os, subprocess, sys
here = os.path.dirname(os.path.abspath(__file__))
fxc = sys.argv[1] if len(sys.argv) > 1 else sorted(glob.glob(r"C:\Program Files (x86)\Windows Kits\10\bin\*\x64\fxc.exe"))[-1]
# (member name, entry point, profile, source file)
shaders = [
    ("fullscreenVS", "FullscreenVS", "vs_5_0", "HCM_TAA.hlsl"),
    ("resolvePS", "ResolvePS", "ps_5_0", "HCM_TAA.hlsl"),
    ("proxyVS", "ProxyVS", "vs_5_0", "HCM_TAAProxy.hlsl"),
    ("proxyPS", "ProxyPS", "ps_5_0", "HCM_TAAProxy.hlsl"),
    ("triVS", "TriVS", "vs_5_0", "HCM_TAAProxy.hlsl"),
    ("triPS", "TriPS", "ps_5_0", "HCM_TAAProxy.hlsl"),
    ("triExtentPS", "TriExtentPS", "ps_5_0", "HCM_TAAProxy.hlsl"),
]
gen = os.path.join(here, "Generated")
os.makedirs(gen, exist_ok=True)
out = ["// GENERATED by TAA\\build_shaders.py from HCM_TAA.hlsl / HCM_TAAProxy.hlsl. Do not edit.", "#pragma once", "#include <cstdint>", "#include <cstddef>", ""]
for member, entry, prof, src in shaders:
    obj = os.path.join(gen, "tmp_%s.cso" % member)
    cmd = [fxc, "/nologo", "/O3", "/WX", "/T", prof, "/E", entry, "/Fo", obj, os.path.join(here, src)]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=here)
    if r.returncode != 0:
        print(r.stdout, r.stderr); raise SystemExit("fxc failed: %s" % member)
    if r.stderr.strip():
        print(r.stderr.strip())
    b = open(obj, "rb").read()
    os.remove(obj)
    out.append("static const uint8_t g_TAA_%s[] = {" % member)
    for i in range(0, len(b), 24):
        out.append("\t" + ", ".join("0x%02X" % x for x in b[i:i + 24]) + ",")
    out.append("};")
    print("%-14s %6d bytes" % (member, len(b)))
out.append("")
out.append("struct TAAShaderBlob { const uint8_t* data; size_t size; };")
out.append("struct TAAShaderSet { TAAShaderBlob " + ", ".join(m for m, _, _, _ in shaders) + "; };")
out.append("static const TAAShaderSet TAAShaders = {")
out.append("\t" + ", ".join("{ g_TAA_%s, sizeof(g_TAA_%s) }" % (m, m) for m, _, _, _ in shaders))
out.append("};")
open(os.path.join(gen, "TAAShaders.h"), "w", newline="\r\n").write("\n".join(out) + "\n")
print("wrote Generated\\TAAShaders.h")
