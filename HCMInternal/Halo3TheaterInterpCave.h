// ================================================================================================
// HALO 3 THEATER INTERPOLATION - the recovered cave, verbatim.
//
// Halo 3 MCC replays Theater at the tick rate, so a watched player TURNING makes the world step.
// Camera POSITION is interpolated by the engine (sub_180184438); camera ORIENTATION is not - it is
// rebuilt each tick from raw unit aiming. Three sites fix the three visible symptoms.
//
// PROVENANCE. This blob was recovered by diffing halo3\moddeddll\halo3.dll (2026-06-18) against
// stock halo3.dll. The build scripts that produced it (build_fpgate.py / build_crouchfix3.py) are
// GONE, so this array and the hook table below are the only surviving copy. The .text diff had 19
// changed runs; the 16 not listed here belong to unrelated mods in that DLL and were EXCLUDED -
// confirmed by diffing against the "dll no crouch" build, in which ONLY the crouch site differs.
//
// THE CAVE IS SELF-RELOCATING, AND THAT USED TO DICTATE WHERE IT MUST LIVE. Each entry does
//     lea r10,[rip] ; movabs rax, <its own linked VA> ; sub r10,rax
// to derive a slide, then adds that slide to every absolute it touches - INCLUDING game addresses.
// Left alone that is only correct at the linked offset, so the cave was pinned to moduleBase +
// kCaveRva. It was a PE section in the modded DLL for that reason.
//
// ⚠ THAT PIN IS A LANDMINE: halo3.dll's SizeOfImage is EXACTLY 0x4768000, so kCaveRva is the page
// immediately PAST the end of the module - unowned address space with nothing reserving it. When
// any other allocation happens to take it the fix cannot arm at all (observed live 2026-09-06:
// "could not reserve the cave at its required address"). kRelocation below lifts the pin; see it
// for why only 13 fixups are needed and why placement is still bounded to +/-2GB.
// ================================================================================================

