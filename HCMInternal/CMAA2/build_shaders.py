# build_shaders.py - precompiles Intel's CMAA2.hlsl (Apache-2.0, see CMAA2_LICENSE.txt) with the Windows SDK's fxc into
# Generated\CMAA2Shaders.h for HCM's post-process anti-aliasing (SMAAPostProcess.cpp, method CMAA2, 2026-11-23).
# One set per quality preset (CMAA2_STATIC_QUALITY_PRESET 0 Low .. 3 Ultra) of the three main compute shaders; the
# dispatch-argument and debug shaders once. Defines as for an 8-bit RGBA frame read through an sRGB view and written with a
# typed R8G8B8A8_UNORM store (the shader's own defaults: CMAA2_UAV_STORE_TYPED 1, _TYPED_UNORM_FLOAT 1, _CONVERT_TO_SRGB 1).
# Run it again only when CMAA2.hlsl changes; the output is checked in.
# usage: python build_shaders.py [path to fxc.exe]
import glob, os, subprocess, sys
here = os.path.dirname(os.path.abspath(__file__))
fxc = sys.argv[1] if len(sys.argv) > 1 else sorted(glob.glob(r"C:\Program Files (x86)\Windows Kits\10\bin\*\x64\fxc.exe"))[-1]
common = ["CMAA2_UAV_STORE_TYPED=1", "CMAA2_UAV_STORE_TYPED_UNORM_FLOAT=1", "CMAA2_UAV_STORE_CONVERT_TO_SRGB=1",
          "CMAA2_SUPPORT_HDR_COLOR_RANGE=0", "CMAA2_EXTRA_SHARPNESS=0"]
# (member name, entry point, extra defines)
shaders = []
for q in range(4):
    for member, entry in (("edges", "EdgesColor2x2CS"), ("process", "ProcessCandidatesCS"), ("apply", "DeferredColorApply2x2CS")):
        shaders.append(("%s%d" % (member, q), entry, ["CMAA2_STATIC_QUALITY_PRESET=%d" % q]))
shaders.append(("dispatchArgs", "ComputeDispatchArgsCS", ["CMAA2_STATIC_QUALITY_PRESET=2"]))
shaders.append(("debugEdges", "DebugDrawEdgesCS", ["CMAA2_STATIC_QUALITY_PRESET=2"]))
gen = os.path.join(here, "Generated")
os.makedirs(gen, exist_ok=True)
out = ["// GENERATED by CMAA2\\build_shaders.py from CMAA2.hlsl (Intel CMAA2, Apache-2.0 - see CMAA2_LICENSE.txt). Do not edit.",
       "#pragma once", "#include <cstdint>", "#include <cstddef>", ""]
for member, entry, defs in shaders:
    obj = os.path.join(gen, "tmp_%s.cso" % member)
    cmd = [fxc, "/nologo", "/O3", "/T", "cs_5_0", "/E", entry]
    for d in common + defs:
        cmd += ["/D", d]
    cmd += ["/Fo", obj, os.path.join(here, "CMAA2.hlsl")]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=here)
    if r.returncode != 0:
        print(r.stdout, r.stderr); raise SystemExit("fxc failed: %s" % member)
    b = open(obj, "rb").read()
    os.remove(obj)
    out.append("static const uint8_t g_CMAA2_%s[] = {" % member)
    for i in range(0, len(b), 24):
        out.append("\t" + ", ".join("0x%02X" % x for x in b[i:i + 24]) + ",")
    out.append("};")
    print("%-14s %6d bytes" % (member, len(b)))
out.append("")
out.append("struct CMAA2ShaderBlob { const uint8_t* data; size_t size; };")
out.append("// per quality preset (0 Low .. 3 Ultra): edges, process candidates, deferred colour apply")
out.append("static const CMAA2ShaderBlob CMAA2Edges[4] = { %s };" % ", ".join("{ g_CMAA2_edges%d, sizeof(g_CMAA2_edges%d) }" % (q, q) for q in range(4)))
out.append("static const CMAA2ShaderBlob CMAA2Process[4] = { %s };" % ", ".join("{ g_CMAA2_process%d, sizeof(g_CMAA2_process%d) }" % (q, q) for q in range(4)))
out.append("static const CMAA2ShaderBlob CMAA2Apply[4] = { %s };" % ", ".join("{ g_CMAA2_apply%d, sizeof(g_CMAA2_apply%d) }" % (q, q) for q in range(4)))
out.append("static const CMAA2ShaderBlob CMAA2DispatchArgs = { g_CMAA2_dispatchArgs, sizeof(g_CMAA2_dispatchArgs) };")
out.append("static const CMAA2ShaderBlob CMAA2DebugEdges = { g_CMAA2_debugEdges, sizeof(g_CMAA2_debugEdges) };")
open(os.path.join(gen, "CMAA2Shaders.h"), "w", newline="\r\n").write("\n".join(out) + "\n")
print("wrote Generated\\CMAA2Shaders.h")
