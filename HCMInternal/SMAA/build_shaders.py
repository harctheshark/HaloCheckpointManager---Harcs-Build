# build_shaders.py - precompiles HCM_SMAA.hlsl with the Windows SDK's fxc into Generated\SMAAShaders.h.
# 2026-11-21: one shader set tuned at run time (threshold / search steps / diagonal steps / corner rounding from the constant
# buffer), was one set per SMAA preset (2026-11-20). Shaders: EdgeVS, LumaEdgePS, ColorEdgePS, BlendVS, BlendPS (diagonals),
# BlendNoDiagPS (BlendPS with /D HCM_NODIAG: SMAA's Low / Medium), NeighborVS, NeighborPS, EdgeDebugPS.
# Run it again only when HCM_SMAA.hlsl / SMAA.hlsl change; the output is checked in.
# usage: python build_shaders.py [path to fxc.exe]
import glob, os, subprocess, sys
here = os.path.dirname(os.path.abspath(__file__))
fxc = sys.argv[1] if len(sys.argv) > 1 else sorted(glob.glob(r"C:\Program Files (x86)\Windows Kits\10\bin\*\x64\fxc.exe"))[-1]
# (member name, entry point, profile, extra defines)
shaders = [
    ("edgeVS", "EdgeVS", "vs_5_0", []),
    ("lumaEdgePS", "LumaEdgePS", "ps_5_0", []),
    ("colorEdgePS", "ColorEdgePS", "ps_5_0", []),
    ("blendVS", "BlendVS", "vs_5_0", []),
    ("blendPS", "BlendPS", "ps_5_0", []),
    ("blendNoDiagPS", "BlendPS", "ps_5_0", ["HCM_NODIAG"]),
    ("neighborVS", "NeighborVS", "vs_5_0", []),
    ("neighborPS", "NeighborPS", "ps_5_0", []),
    ("edgeDebugPS", "EdgeDebugPS", "ps_5_0", []),
    # 2026-11-21: depth predication (the game's depth via GameDepthTap)
    ("depthLogPS", "DepthLogPS", "ps_5_0", []),
    ("lumaEdgePredPS", "LumaEdgePS", "ps_5_0", ["HCM_PRED"]),
    ("colorEdgePredPS", "ColorEdgePS", "ps_5_0", ["HCM_PRED"]),
]
gen = os.path.join(here, "Generated")
os.makedirs(gen, exist_ok=True)
out = ["// GENERATED by SMAA\\build_shaders.py from HCM_SMAA.hlsl (SMAA, MIT - see SMAA_LICENSE.txt). Do not edit.", "#pragma once", "#include <cstdint>", ""]
for member, entry, prof, defs in shaders:
    obj = os.path.join(gen, "tmp_%s.cso" % member)
    cmd = [fxc, "/nologo", "/O3", "/T", prof, "/E", entry]
    for d in defs:
        cmd += ["/D", d]
    cmd += ["/Fo", obj, os.path.join(here, "HCM_SMAA.hlsl")]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=here)
    if r.returncode != 0:
        print(r.stdout, r.stderr); raise SystemExit("fxc failed: %s" % member)
    if r.stderr.strip():
        print(r.stderr.strip())
    b = open(obj, "rb").read()
    os.remove(obj)
    out.append("static const uint8_t g_SMAA_%s[] = {" % member)
    for i in range(0, len(b), 24):
        out.append("\t" + ", ".join("0x%02X" % x for x in b[i:i + 24]) + ",")
    out.append("};")
    print("%-14s %6d bytes" % (member, len(b)))
out.append("")
out.append("struct SMAAShaderBlob { const uint8_t* data; size_t size; };")
out.append("struct SMAAShaderSet { SMAAShaderBlob " + ", ".join(m for m, _, _, _ in shaders) + "; };")
out.append("static const SMAAShaderSet SMAAShaders = {")
out.append("\t" + ", ".join("{ g_SMAA_%s, sizeof(g_SMAA_%s) }" % (m, m) for m, _, _, _ in shaders))
out.append("};")
open(os.path.join(gen, "SMAAShaders.h"), "w", newline="\r\n").write("\n".join(out) + "\n")
print("wrote Generated\\SMAAShaders.h")
